-- GÉNÉRATION AUTOMATIQUE POUR LES 43 AUTRES ÉQUIPES
-- Cette requête remplit toutes les équipes qui n'ont pas encore de joueurs
-- -------------------------------------------------------------
INSERT INTO players (name, player_position, shirt_number, current_team_id)
SELECT
    CONCAT(
            CASE
                WHEN n.num = 1 THEN 'Gardien '
                WHEN n.num BETWEEN 2 AND 7 THEN 'Def '
                WHEN n.num BETWEEN 8 AND 13 THEN 'Milieu '
                ELSE 'Att '
                END,
            t.short_name, ' #', n.num
    ) AS name,
    CASE
        WHEN n.num = 1 THEN 'Goalkeeper'
        WHEN n.num BETWEEN 2 AND 7 THEN 'Defender'
        WHEN n.num BETWEEN 8 AND 13 THEN 'Midfielder'
        ELSE 'Attacker'
        END AS player_position,
    n.num AS shirt_number,
    t.id AS current_team_id
FROM teams t
         CROSS JOIN (
    SELECT 1 AS num UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6
    UNION SELECT 7 UNION SELECT 8 UNION SELECT 9 UNION SELECT 10 UNION SELECT 11 UNION SELECT 12
    UNION SELECT 13 UNION SELECT 14 UNION SELECT 15 UNION SELECT 16 UNION SELECT 17 UNION SELECT 18
) n
WHERE t.id NOT IN (33, 9, 37, 41, 45); -- On exclut France, Brésil, Argentine, Portugal, Angleterre qui sont déjà faits